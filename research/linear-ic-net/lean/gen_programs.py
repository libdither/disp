"""Writes Programs.lean, the hand-written programs from ../nets/check.py as de Bruijn terms, and
Readers.lean, random programs that read values and use the parts (the same generator check.py tests with)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'nets'))
import random
from check import program, TESTS, gen, run_net

def debruijn(t, env=()):
    if t == 'ρ': return 'Tm.rho'
    if isinstance(t, str): return f'(Tm.var {env.index(t)})'
    if len(t) == 3: return f'(Tm.{"Lam" if t[0] == "Λ" else "lam"} {debruijn(t[2], (t[1],) + env)})'
    return f'(Tm.app {debruijn(t[0], env)} {debruijn(t[1], env)})'

# the interpreter runs are long (up to millions of steps), so they get their own list and their own build target
LONG = ('interpret: binders in suc', 'interpret the interpreter', 'interpret the interpreter, reading')
lines = ['import Check', '', '/-! Generated by `gen_programs.py` from `../nets/check.py`; do not edit. -/', '']
for listname, keep in (('programs', lambda n: n not in LONG), ('longPrograms', lambda n: n in LONG)):
    chosen = [(n, src) for n, src in TESTS if keep(n)]
    lines.append(f'def {listname} : List (String × Tm) := [')
    for i, (name, src) in enumerate(chosen):
        lines.append(f'  ("{name}", {debruijn(program(src))}){"," if i < len(chosen) - 1 else ""}')
    lines += [']', '']
open(os.path.join(here, 'Programs.lean'), 'w').write('\n'.join(lines))
print(len(TESTS), 'programs written')

# 250 random readers, then more picked because they use the rules that few programs use: for each such
# rule, the 120 shortest runs among 40,000 random readers that fire it
RARE = ('copy app by sig', 'copy var by sig', 'copy Lam by sig', 'copy Lam by dup', 'copy sig by dup',
        'copy app by dup', 'copy rho by dup', 'erase dup')
rng = random.Random(5)
terms = [gen(rng, rng.randint(4, 16), [], True, True) for _ in range(250)]
found = {k: [] for k in RARE}
for _ in range(40000):
    t = gen(rng, rng.randint(4, 14), [], True, True)
    status, _, stats = run_net(t, None, 3000)
    if status not in ('done', 'stuck'): continue
    for k in RARE:
        if stats[k]: found[k].append((stats['interactions'], len(str(t)), t))
picked = []
for k in RARE:
    best = sorted(found[k], key=lambda e: e[:2])[:120]
    picked += [t for _, _, t in best if t not in picked and t not in terms]
    print(f'  {k}: {len(found[k])} of 40000 fire it')
terms += picked
# Code arriving at a split: quote a random application (or a lone variable) with a written-out opened
# function, and hand both copies back, so the answer shows each copy whole.
for i in range(160):
    body = 'd'
    while i % 8 and not (isinstance(body, tuple) and len(body) == 2):
        body = gen(rng, rng.randint(3, 9), ['d'], True, False)
    arg = gen(rng, rng.randint(1, 3), [], True, False)
    terms.append((('λ', 'c', ('λ', 'k', (('k', 'c'), 'c'))), (('Λ', 'd', body), arg)))
lines = ['import Check', '', '/-! Generated by `gen_programs.py` with the generator of `../nets/check.py`; do not edit. -/', '',
         'set_option maxRecDepth 100000', '', 'def randomReaders : List Tm := [']
for i, t in enumerate(terms):
    lines.append(f'  {debruijn(t)}{"," if i < len(terms) - 1 else ""}')
lines.append(']')
open(os.path.join(here, 'Readers.lean'), 'w').write('\n'.join(lines) + '\n')
print(len(terms), 'random readers written')
