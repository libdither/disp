#!/usr/bin/env bash
# Compile the strand lattice to WebAssembly and embed it in player/engine.js, so player/index.html opens
# straight from disk and runs the engine the tests check; then the linear net's generated parts: the rules
# into tree-net (lin/gen-rust.mts, run first) and the page's compiler (lin/bundle.mts). The disp programs
# (programs.js, compiler.js) are as they were copied from rust-ic-strands.
set -euo pipefail
self="$(readlink -f "$0")"
here="$(dirname "$self")"
(cd "$here/../.." && npx --prefix website tsx evaluators/rust-ic-linear-strands/lin/gen-rust.mts)
cd "$here/crate"
if ! command -v wasm-ld >/dev/null; then
  exec nix shell nixpkgs#lld -c "$self" "$@"
fi
export CARGO_TARGET_WASM32_UNKNOWN_UNKNOWN_LINKER=wasm-ld
cargo rustc --lib --profile wasm --target wasm32-unknown-unknown --crate-type cdylib -q
wasm=target/wasm32-unknown-unknown/wasm/rust_ic_strands.wasm
{
  printf '// generated by build-player.sh from the rust-ic-linear-strands crate; do not edit\n'
  printf 'window.STRANDS_WASM = "'
  base64 -w0 "$wasm"
  printf '";\n'
} > ../player/engine.js
echo "player/engine.js: $(stat -c %s "$wasm") bytes of wasm"
(cd "$here/../.." && npx --prefix website tsx evaluators/rust-ic-linear-strands/lin/bundle.mts)
