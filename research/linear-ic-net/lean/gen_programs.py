"""Writes Programs.lean: the hand-written reflective programs from ../nets/check.py as de Bruijn terms.
Free names there are symbols; the Lean design has no symbol agent, so each becomes a small closed value."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'nets'))
from check import program, TESTS

STANDINS = {'u': ('λ', 'z', 'z'), 'w': ('λ', 'y', ('λ', 'z', 'y')), 'l': ('λ', 'z', 'z'), 'mark': ('λ', 'z', 'z')}

def debruijn(t, env=()):
    if t == 'ρ': return 'Tm.rho'
    if isinstance(t, str):
        if t in env: return f'(Tm.var {env.index(t)})'
        return debruijn(STANDINS[t], ())
    if len(t) == 3: return f'(Tm.lam {debruijn(t[2], (t[1],) + env)})'
    return f'(Tm.app {debruijn(t[0], env)} {debruijn(t[1], env)})'

lines = ['import Check', '', '/-! Generated by `gen_programs.py` from `../nets/check.py`; do not edit. -/', '',
         'def programs : List (String × Tm) := [']
for i, (name, src) in enumerate(TESTS):
    lines.append(f'  ("{name}", {debruijn(program(src))}){"," if i < len(TESTS) - 1 else ""}')
lines.append(']')
open(os.path.join(here, 'Programs.lean'), 'w').write('\n'.join(lines) + '\n')
print(len(TESTS), 'programs written')
