//! Writes `hw/rtl/strands_tables.vh`: the rules, the chip's energies and probabilities, and the
//! acceptance table, from the simulator's own definitions, so the chip and the simulator cannot
//! drift apart on them.
use rust_ca_lattice::rules::{End, Tag, ALL_TAGS, RULES};
use rust_ic_strands::lattice::{chip, fresh_wanted, Energy};
use std::fmt::Write;

fn code(t: Tag) -> usize { ALL_TAGS.iter().position(|x| *x == t).unwrap() + 1 }

/// An end of a rule wire in 8 bits: kind (0 fresh, 1 consumer aux, 2 producer aux), fresh agent, port.
fn end(e: End) -> u32 {
    match e {
        End::Fresh(f, q) => (f as u32) << 3 | q as u32,
        End::CAux(i) => 1 << 6 | i as u32,
        End::PAux(i) => 2 << 6 | i as u32,
    }
}

fn main() {
    let p = chip();
    let e = Energy::new(&p);
    let chance = |x: f64| (x * 256.0).round() as u32;
    let mut v = String::new();
    let w = &mut v;
    writeln!(w, "// Generated by `cargo run --bin strands-hw` from the simulator's rules and chip configuration; do not edit.").unwrap();
    writeln!(w, "localparam integer E_PRINCIPAL = {}, E_PRINCIPAL_IDLE = {}, E_AUX = {}, E_AUX_IDLE = {};", e.principal[0], e.principal[1], e.aux[0], e.aux[1]).unwrap();
    writeln!(w, "localparam integer E_CROWD = {}, E_IDLE = {}, E_LINK = {}, E_BOARD = {};", e.crowd, e.idle, e.link, e.board).unwrap();
    assert!(e.pressure == 0 && e.repel == 0, "the chip has no pressure or repulsion");
    writeln!(w, "localparam integer CH_ACTIVE = {}, CH_HOP = {}, CH_ALONG = {}, CH_SWAP = {};", chance(p.active), chance(p.p_hop), chance(0.7), chance(p.swap)).unwrap();
    writeln!(w, "localparam integer PAIRS = {}, LAZY = {}, GC = {};", p.pairs, p.lazy as u8, p.gc as u8).unwrap();
    writeln!(w, "localparam integer ACCEPT_LEN = {};", e.accept.len()).unwrap();
    writeln!(w, "function [15:0] accept_thr(input [7:0] d);\n  case (d)").unwrap();
    for (d, a) in e.accept.iter().enumerate() { writeln!(w, "    {d}: accept_thr = 16'd{a};").unwrap(); }
    writeln!(w, "    default: accept_thr = 16'd0;\n  endcase\nendfunction").unwrap();

    writeln!(w, "function [4:0] rule_of(input [3:0] ct, input [3:0] pt);\n  case ({{ct, pt}})").unwrap();
    for (i, r) in RULES.iter().enumerate() { writeln!(w, "    {{4'd{}, 4'd{}}}: rule_of = 5'd{i}; // {}·{}", code(r.consumer), code(r.producer), r.consumer.name(), r.producer.name()).unwrap(); }
    writeln!(w, "    default: rule_of = 5'd31;\n  endcase\nendfunction").unwrap();
    let table = |w: &mut String, name: &str, width: u32, args: &str, sel: &str, rows: Vec<(String, u32)>| {
        writeln!(w, "function [{}:0] {name}({args});\n  case ({sel})", width - 1).unwrap();
        for (k, val) in rows { writeln!(w, "    {k}: {name} = {width}'d{val};").unwrap(); }
        writeln!(w, "    default: {name} = {width}'d0;\n  endcase\nendfunction").unwrap();
    };
    table(w, "rule_n", 3, "input [4:0] ri", "ri", RULES.iter().enumerate().map(|(i, r)| (format!("{i}"), r.fresh.len() as u32)).collect());
    table(w, "rule_nw", 4, "input [4:0] ri", "ri", RULES.iter().enumerate().map(|(i, r)| (format!("{i}"), r.wires.len() as u32)).collect());
    table(w, "rule_wanted", 6, "input [4:0] ri", "ri", RULES.iter().enumerate()
        .map(|(i, r)| (format!("{i}"), fresh_wanted(r).iter().enumerate().fold(0, |m, (f, &b)| m | (b as u32) << f))).collect());
    let mut rows = vec![];
    for (i, r) in RULES.iter().enumerate() { for (f, t) in r.fresh.iter().enumerate() { rows.push((format!("{{5'd{i}, 3'd{f}}}"), code(*t) as u32)); } }
    table(w, "rule_fresh", 4, "input [4:0] ri, input [2:0] f", "{ri, f}", rows);
    for (name, pick) in [("rule_wa", 0), ("rule_wb", 1)] {
        let mut rows = vec![];
        for (i, r) in RULES.iter().enumerate() {
            for (k, &(a, b)) in r.wires.iter().enumerate() { rows.push((format!("{{5'd{i}, 4'd{k}}}"), end(if pick == 0 { a } else { b }))); }
        }
        table(w, name, 8, "input [4:0] ri, input [3:0] k", "{ri, k}", rows);
    }
    if std::env::args().nth(1).as_deref() == Some("--wgsl") {
        print!("{}", rust_ic_strands::tables::wgsl());
        return;
    }
    let out = std::env::args().nth(1).unwrap_or_else(|| "../hw/rtl/strands_tables.vh".into());
    std::fs::write(&out, v).expect("write tables");
    eprintln!("wrote {out}");
}
